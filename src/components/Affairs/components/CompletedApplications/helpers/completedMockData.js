const now = new Date();
function offsetDate(days) {
  const d = new Date(now);
  d.setDate(d.getDate() + days);
  return d.toISOString().split('T')[0];
}

function offsetIsoTime(days, hoursAgo = 0) {
  const d = new Date(now);
  d.setDate(d.getDate() + days);
  d.setHours(d.getHours() - hoursAgo);
  return d.toISOString();
}

